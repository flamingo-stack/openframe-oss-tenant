#!/usr/bin/env node
/**
 * Syncs the daemon's current agent token into `.env.development.local`, for
 * `npm run frontend:dev` — the browser-only mode where Tauri `invoke` is
 * unavailable and `tokenService` can only fall back to `import.meta.env`.
 *
 * The desktop shell does NOT need this: Rust decrypts the same file itself and
 * follows its rotation (see src-tauri/src/token_watcher.rs). Seeding VITE_TOKEN
 * for `tauri dev` pins a token that goes stale within the hour.
 *
 * Source of truth is the daemon's AES-256-GCM token file, located via macOS
 * CFPreferences. On other platforms, pass the same values as env vars:
 * OPENFRAME_TOKEN_PATH, OPENFRAME_SECRET, OPENFRAME_SERVER_URL.
 */

import { execFileSync } from 'node:child_process';
import { createDecipheriv } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const BUNDLE_ID = 'com.openframe.chat';
const AGENT_CONFIG_PATH = '/Library/Application Support/OpenFrame/secured/agent_config.json';
const OUTPUT_FILE = '.env.development.local';
const NONCE_BYTES = 12;
const TAG_BYTES = 16;

/** Reads a single key from the daemon's macOS preferences domain. */
function readPreference(key) {
  if (process.platform !== 'darwin') return null;
  try {
    const value = execFileSync('defaults', ['read', BUNDLE_ID, key], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    return value.trim() || null;
  } catch {
    return null;
  }
}

/** Decrypts the daemon's token file: base64(nonce || ciphertext || tag). */
function decryptTokenFile(path, secret) {
  const combined = Buffer.from(readFileSync(path, 'utf8').trim(), 'base64');
  if (combined.length < NONCE_BYTES + TAG_BYTES) {
    throw new Error(`encrypted token too short (${combined.length} bytes)`);
  }

  const nonce = combined.subarray(0, NONCE_BYTES);
  const ciphertext = combined.subarray(NONCE_BYTES, combined.length - TAG_BYTES);
  const tag = combined.subarray(combined.length - TAG_BYTES);

  const decipher = createDecipheriv('aes-256-gcm', Buffer.from(secret, 'utf8'), nonce);
  decipher.setAuthTag(tag);
  return Buffer.concat([decipher.update(ciphertext), decipher.final()]).toString('utf8');
}

function readClaims(token) {
  const payload = token.split('.')[1];
  if (!payload) throw new Error('token is not a JWT');
  return JSON.parse(Buffer.from(payload, 'base64url').toString('utf8'));
}

function maskToken(token) {
  return `${token.slice(0, 12)}…${token.slice(-8)} (${token.length} chars)`;
}

function fail(message, hint) {
  console.error(`✗ ${message}`);
  if (hint) console.error(`  ${hint}`);
  process.exit(1);
}

const tokenPath = process.env.OPENFRAME_TOKEN_PATH ?? readPreference('openframe-token-path');
const secret = process.env.OPENFRAME_SECRET ?? readPreference('openframe-secret');
const serverUrl = process.env.OPENFRAME_SERVER_URL ?? readPreference('serverUrl');

if (!serverUrl) {
  fail(
    `no serverUrl configured for ${BUNDLE_ID}`,
    'Is the openframe-client daemon installed? Otherwise set OPENFRAME_SERVER_URL.',
  );
}

let token = null;
let source = null;

// Preferred source — the same encrypted file the desktop shell reads.
if (tokenPath && secret && existsSync(tokenPath)) {
  if (secret.length !== 32) {
    fail(`secret must be exactly 32 bytes, got ${secret.length}`, 'Check the openframe-secret preference.');
  }
  try {
    token = decryptTokenFile(tokenPath, secret);
    source = tokenPath;
  } catch (error) {
    console.warn(`! could not decrypt ${tokenPath}: ${error.message}`);
  }
}

// Fallback — the daemon writes the same access_token here in plain JSON.
if (!token && existsSync(AGENT_CONFIG_PATH)) {
  try {
    token = JSON.parse(readFileSync(AGENT_CONFIG_PATH, 'utf8')).access_token ?? null;
    source = AGENT_CONFIG_PATH;
  } catch (error) {
    console.warn(`! could not read ${AGENT_CONFIG_PATH}: ${error.message}`);
  }
}

if (!token) {
  fail('no token found', `Looked in ${tokenPath ?? '<no token path>'} and ${AGENT_CONFIG_PATH}.`);
}

const claims = readClaims(token);
const expiresAt = new Date(claims.exp * 1000);
const minutesLeft = Math.round((expiresAt.getTime() - Date.now()) / 60_000);

writeFileSync(
  resolve(process.cwd(), OUTPUT_FILE),
  [
    '# Generated by `npm run token:sync` — do not commit, do not edit by hand.',
    '# Only read by `npm run frontend:dev`; the Tauri shell gets its token from Rust.',
    `VITE_SERVER_URL=${serverUrl}`,
    `VITE_TOKEN=${token}`,
    '',
  ].join('\n'),
);

console.log(`✓ wrote ${OUTPUT_FILE}`);
console.log(`  source     ${source}`);
console.log(`  serverUrl  ${serverUrl}`);
console.log(`  machineId  ${claims.machine_id ?? '<none>'}`);
console.log(`  token      ${maskToken(token)}`);
// Local time first: the daemon rotates hourly, and a UTC-only stamp next to a
// local clock reads as "already expired" in any timezone ahead of UTC.
const expiresLocal = expiresAt.toLocaleTimeString(undefined, { hour12: false });
console.log(
  minutesLeft > 0
    ? `  expires    ${expiresLocal} local / ${expiresAt.toISOString()} — valid for ${minutesLeft} more min`
    : `  expires    ${expiresLocal} local / ${expiresAt.toISOString()} — ALREADY EXPIRED, daemon has not rotated it yet`,
);

const envPath = resolve(process.cwd(), '.env');
if (existsSync(envPath) && /^VITE_TOKEN=.+$/m.test(readFileSync(envPath, 'utf8'))) {
  console.warn('\n! .env also sets VITE_TOKEN. This file wins, but clear .env to avoid confusion —');
  console.warn('  and note .env is read by `npm run build` too, which bakes the token into the bundle.');
}
